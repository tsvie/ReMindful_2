const app = {
    data: {
        user: null,
        entries: [],
        activeGoals: [],
        currentLang: 'de',
        selectedMood: null,
        currentGoalType: 'daily'
    },

    init: function() {
        this.loadData();
        this.applyLanguage();

        if (this.data.user && this.data.user.name) {
            document.getElementById('screen-onboarding').style.display = 'none';
            this.showSplash();
        } else {
            document.getElementById('screen-onboarding').style.display = 'flex';
            document.getElementById('screen-main').style.display = 'none';
        }
    },

    // --- UTILS ---
    safeParse: function(key, defaultValue) {
        try {
            const item = localStorage.getItem(key);
            return item ? JSON.parse(item) : defaultValue;
        } catch (e) {
            return defaultValue;
        }
    },
    loadData: function() {
        this.data.user = this.safeParse('aw_user', null);
        this.data.entries = this.safeParse('aw_entries', []);
        this.data.activeGoals = this.safeParse('aw_active_goals', []);
        if(this.data.user && this.data.user.lang) this.data.currentLang = this.data.user.lang;
    },
    saveData: function() {
        localStorage.setItem('aw_user', JSON.stringify(this.data.user));
        localStorage.setItem('aw_entries', JSON.stringify(this.data.entries));
        localStorage.setItem('aw_active_goals', JSON.stringify(this.data.activeGoals));
    },

    // --- UI HELPERS ---
    showToast: function(message) {
        const c = document.getElementById('toast-container');
        const t = document.createElement('div');
        t.className = 'toast';
        t.innerText = message;
        c.appendChild(t);
        setTimeout(() => t.remove(), 3000);
    },

    showModal: function(title, bodyHTML, onConfirm, showCancel = true) {
        document.getElementById('modal-title').innerText = title;
        document.getElementById('modal-body').innerHTML = bodyHTML;
        document.getElementById('custom-modal').style.display = 'flex';

        const btnCancel = document.getElementById('modal-cancel');
        const btnConfirm = document.getElementById('modal-confirm');

        btnCancel.style.display = showCancel ? 'block' : 'none';

        btnCancel.onclick = () => { document.getElementById('custom-modal').style.display = 'none'; };
        btnConfirm.onclick = () => {
            if(onConfirm) onConfirm();
            document.getElementById('custom-modal').style.display = 'none';
        };
    },

    // --- I18N ---
    setLang: function(lang) {
        this.data.currentLang = lang;
        document.querySelectorAll('.lang-selector .lang-btn').forEach(b => b.classList.remove('active'));
        event.target.classList.add('active');
        this.applyLanguage();
    },
    changeLang: function(lang) {
        this.data.user.lang = lang;
        this.data.currentLang = lang;
        this.saveData();
        this.applyLanguage();
        this.showToast(this.t('settings_name_btn') + " ✅");
    },
    t: function(key) {
        return i18n[this.data.currentLang][key] || key;
    },
    applyLanguage: function() {
        const langData = i18n[this.data.currentLang];
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if(langData[key]) el.innerText = langData[key];
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if(langData[key]) el.placeholder = langData[key];
        });
    },

    // --- ONBOARDING & SPLASH ---
    finishOnboarding: function() {
        const name = document.getElementById('input-username').value.trim();
        if (name) {
            this.data.user = { name: name, lang: this.data.currentLang };
            this.saveData();
            document.getElementById('screen-onboarding').style.display = 'none';
            this.showSplash();
        } else {
            this.showToast("Bitte gib einen Namen ein.");
        }
    },
    showSplash: function() {
        const splash = document.getElementById('screen-splash');
        document.getElementById('splash-title').innerText = `${this.t('welcome') || 'Willkommen'} ${this.data.user.name}!`;
        splash.style.display = 'flex';
    },
    closeSplash: function() {
        document.getElementById('screen-splash').style.display = 'none';
        document.getElementById('screen-main').style.display = 'flex';
        this.switchTab('mood', document.querySelector('.bottom-nav button'));
        this.renderActiveGoals();
    },

    // --- TABS ---
    switchTab: function(tabId, btnElement) {
        document.querySelectorAll('.tab-content').forEach(tab => tab.style.display = 'none');
        document.querySelectorAll('.bottom-nav button').forEach(btn => btn.classList.remove('active'));
        document.getElementById('tab-' + tabId).style.display = 'block';
        if(btnElement) btnElement.classList.add('active');
        if(tabId === 'journal') this.renderJournal();
        if(tabId === 'settings') {
            document.getElementById('settings-name').value = this.data.user.name;
            document.querySelectorAll('#tab-settings .lang-btn').forEach(b => b.classList.remove('active'));
            document.getElementById(`set-lang-${this.data.currentLang}`).classList.add('active');
        }
    },

    // --- MOOD ---
    selectMood: function(level) {
        this.data.selectedMood = level;
        document.querySelectorAll('.mood-selector button').forEach(b => b.classList.remove('selected'));
        document.querySelector(`.mood-selector button[data-val="${level}"]`).classList.add('selected');
    },

    openMoodNLP: function() {
        const body = `
            <p style="margin-bottom:10px; font-size:14px;">Beschreibe kurz in Stichworten, was los ist. Wir helfen dir, das Gefühl zu benennen.</p>
            <textarea id="nlp-mood-input" placeholder="z.B. Chef war gemein, viel Arbeit..." style="width:100%; min-height:80px;"></textarea>
        `;
        this.showModal("Gefühle analysieren", body, () => {
            const text = document.getElementById('nlp-mood-input').value.toLowerCase();
            let emotion = "Ich fühle mich aufgewühlt und muss meine Gedanken ordnen.";
            if(text.includes('chef') || text.includes('arbeit') || text.includes('stress')) {
                emotion = "Ich fühle mich gestresst und wünsche mir mehr Anerkennung und Ruhe.";
            } else if (text.includes('streit') || text.includes('partner') || text.includes('freund')) {
                emotion = "Ich bin traurig über den Konflikt und wünsche mir Harmonie.";
            }
            // Übernehmen in Textfeld
            const mainText = document.getElementById('mood-text');
            mainText.value = mainText.value ? mainText.value + "\n\n" + emotion : emotion;
            this.showToast("Gefühl übernommen!");
        });
    },

    saveMood: function() {
        if(!this.data.selectedMood) return this.showToast("Bitte wähle einen Emoji aus.");

        const happened = document.getElementById('mood-text').value;
        const pos = document.getElementById('mood-pos').value;
        const neg = document.getElementById('mood-neg').value;

        let fullText = happened;
        if(pos) fullText += `\n\nPositiv: ${pos}`;
        if(neg) fullText += `\n\nNegativ: ${neg}`;

        // Emoji Map
        const emojiMap = {1:'😢', 2:'😕', 3:'😐', 4:'🙂', 5:'😄'};

        this.data.entries.push({
            id: Date.now(),
            type: 'mood',
            moodVal: this.data.selectedMood,
            moodEmoji: emojiMap[this.data.selectedMood],
            text: fullText,
            timestamp: new Date().toISOString()
        });

        this.saveData();
        this.showToast("Stimmung gespeichert!");

        // Reset
        this.data.selectedMood = null;
        document.querySelectorAll('.mood-selector button').forEach(b => b.classList.remove('selected'));
        document.getElementById('mood-text').value = '';
        document.getElementById('mood-pos').value = '';
        document.getElementById('mood-neg').value = '';
    },

    // --- GOALS ---
    switchGoalType: function(type) {
        this.data.currentGoalType = type;
        document.getElementById('seg-daily').classList.toggle('active', type === 'daily');
        document.getElementById('seg-weekly').classList.toggle('active', type === 'weekly');
    },

    nlpAnalyzeGoal: function() {
        const text = document.getElementById('goal-input').value.toLowerCase();
        const container = document.getElementById('goal-nlp-suggestions');
        const saveBtn = document.getElementById('btn-save-goal-direct');

        if(!text) return this.showToast("Bitte gib ein Ziel ein.");

        let goalName = text.trim();
        goalName = goalName.charAt(0).toUpperCase() + goalName.slice(1);

        let html = '';

        // --- Präzises NLP Regelwerk für Ziele ---

        // 1. Haushalt / Aufräumen
        if (text.match(/(aufräumen|putzen|sauber|müll|spülen|staubsaugen|wäsche|waschen|küche|bad|zimmer)/)) {
            html += `<label><input type="checkbox" value="Müllbeutel/Korb holen und in die Mitte des Raumes stellen"> Müllbeutel/Korb holen und in die Mitte stellen</label><br>
                     <label><input type="checkbox" value="Nur eine einzige kleine Fläche (z.B. Tisch) freiräumen"> Nur eine einzige kleine Fläche freiräumen</label><br>
                     <label><input type="checkbox" value="Wecker auf 5 Minuten stellen und danach sofort aufhören"> Wecker auf 5 Minuten stellen und aufhören</label>`;
        }
        // 2. Orga / Büro / Finanzen / Mails
        else if (text.match(/(steuer|rechnung|email|mail|post|brief|anruf|telefon|amt|bank|überweisung|orga)/)) {
            html += `<label><input type="checkbox" value="Alle benötigten Unterlagen/Briefe auf einen Stapel legen"> Alle Unterlagen/Briefe auf einen Stapel legen</label><br>
                     <label><input type="checkbox" value="Nur das Programm öffnen / die Nummer eintippen (ohne anzurufen)"> Nur das Programm öffnen / Nummer eintippen</label><br>
                     <label><input type="checkbox" value="Nur eine einzige E-Mail/Rechnung lesen"> Nur eine einzige E-Mail/Rechnung lesen</label>`;
        }
        // 3. Sport / Gesundheit
        else if (text.match(/(sport|laufen|training|fitness|joggen|yoga|workout|dehnen|spazieren|gym)/)) {
            html += `<label><input type="checkbox" value="Nur die Sportkleidung anziehen und 2 Minuten spüren, wie es sich anfühlt"> Nur die Sportkleidung anziehen</label><br>
                     <label><input type="checkbox" value="Die Trinkflasche füllen und die Yogamatte/Schuhe bereitlegen"> Wasser füllen & Matte/Schuhe bereitlegen</label><br>
                     <label><input type="checkbox" value="Für nur 2 Minuten sanft bewegen (danach ist Schluss)"> Für nur 2 Minuten sanft bewegen</label>`;
        }
        // 4. Lernen / Arbeit / Projekte
        else if (text.match(/(lernen|hausaufgaben|studium|arbeiten|präsentation|schreiben|lesen|programmieren|projekt)/)) {
            html += `<label><input type="checkbox" value="Handy für 10 Minuten in einen anderen Raum legen"> Handy für 10 Min in anderen Raum legen</label><br>
                     <label><input type="checkbox" value="Nur das Dokument/Buch öffnen und exakt einen Absatz lesen/schreiben"> Nur Dokument öffnen & 1 Absatz lesen/schreiben</label><br>
                     <label><input type="checkbox" value="Nur die allererste Überschrift oder den ersten Satz verfassen"> Nur den allerersten Satz schreiben</label>`;
        }
        // 5. Selfcare / Entspannung
        else if (text.match(/(entspannen|schlafen|meditation|baden|pause|ausruhen|abschalten)/)) {
            html += `<label><input type="checkbox" value="Alle Bildschirme und Lichter für 5 Minuten ausschalten"> Alle Bildschirme für 5 Minuten ausschalten</label><br>
                     <label><input type="checkbox" value="Ein großes Glas Wasser trinken und 5 tiefe Atemzüge nehmen"> Wasser trinken & 5 tiefe Atemzüge</label><br>
                     <label><input type="checkbox" value="Für 2 Minuten einfach nur aus dem Fenster schauen"> Für 2 Minuten aus dem Fenster schauen</label>`;
        }
        // 6. Kochen / Ernährung
        else if (text.match(/(kochen|essen|einkaufen|supermarkt|ernährung|rezept)/)) {
            html += `<label><input type="checkbox" value="Nur einen Zettel nehmen und maximal 5 Zutaten aufschreiben"> Nur max. 5 Zutaten aufschreiben</label><br>
                     <label><input type="checkbox" value="Nur die Pfanne/den Topf und das Öl auf den Herd stellen"> Nur Pfanne/Topf auf den Herd stellen</label><br>
                     <label><input type="checkbox" value="Ein Rezept wählen, das weniger als 15 Minuten dauert"> Rezept unter 15 Minuten Dauer wählen</label>`;
        }
        // Fallback (generisch, aber hoch motivierend)
        else {
            html += `<label><input type="checkbox" value="Alle Hilfsmittel für '${goalName}' liebevoll auf den Tisch legen"> Alle Hilfsmittel für dieses Ziel bereitlegen</label><br>
                     <label><input type="checkbox" value="Den allerersten Schritt notieren, der unter 2 Minuten dauert"> Einen Schritt notieren, der unter 2 Minuten dauert</label><br>
                     <label><input type="checkbox" value="Einen Timer auf 3 Minuten stellen und sanft beginnen"> 3-Minuten-Timer stellen und sanft beginnen</label>`;
        }

        if(html) {
             container.innerHTML = html + `<button class="save-btn" onclick="app.saveGoalNLP()" style="margin-top:10px;">Diese Schritte übernehmen</button>`;
             saveBtn.style.display = 'none';
             document.getElementById('custom-step-container').style.display = 'block';
        }
    },

    addCustomStep: function() {
        const stepText = document.getElementById('custom-step-input').value.trim();
        if(!stepText) return;

        const container = document.getElementById('goal-nlp-suggestions');
        const newLabel = document.createElement('label');
        newLabel.innerHTML = `<input type="checkbox" value="${stepText}" checked> ${stepText}`;

        // Insert before the save button
        const saveBtn = container.querySelector('.save-btn');
        if(saveBtn) {
            container.insertBefore(newLabel, saveBtn);
            container.insertBefore(document.createElement('br'), saveBtn);
        } else {
            container.appendChild(newLabel);
        }

        document.getElementById('custom-step-input').value = '';
    },

    saveGoalDirect: function() {
        const text = document.getElementById('goal-input').value;
        if(text) {
            this.addActiveGoal(text, []);
            document.getElementById('goal-input').value = '';
        }
    },

    saveGoalNLP: function() {
        const text = document.getElementById('goal-input').value;
        const checkboxes = document.querySelectorAll('#goal-nlp-suggestions input:checked');
        let steps = Array.from(checkboxes).map(cb => cb.value);

        this.addActiveGoal(text, steps);

        document.getElementById('goal-input').value = '';
        document.getElementById('goal-nlp-suggestions').innerHTML = '';
        document.getElementById('btn-save-goal-direct').style.display = 'block';
    },

    addActiveGoal: function(title, steps) {
        this.data.activeGoals.push({
            id: Date.now(),
            type: this.data.currentGoalType,
            title: title,
            steps: steps,
            timestamp: new Date().toISOString()
        });
        this.saveData();
        this.showToast("Zu aktiven Zielen hinzugefügt!");
        this.renderActiveGoals();
    },

    renderActiveGoals: function() {
        const container = document.getElementById('active-goals-list');
        container.innerHTML = '';
        if(this.data.activeGoals.length === 0) {
            container.innerHTML = '<p style="text-align:center; opacity:0.6;">Keine aktiven Ziele.</p>';
            return;
        }

        this.data.activeGoals.forEach(g => {
            let stepsHtml = '';
            if(g.steps.length > 0) {
                stepsHtml = '<ul>' + g.steps.map(s => `<li>${s}</li>`).join('') + '</ul>';
            }

            const typeTranslated = g.type === 'daily' ? this.t('goals_daily').toUpperCase() : this.t('goals_weekly').toUpperCase();

            const div = document.createElement('div');
            div.className = 'active-goal-card';
            div.innerHTML = `
                <div style="display:flex; justify-content:space-between;">
                    <span class="badge goal">${typeTranslated}</span>
                </div>
                <h4 style="margin-top:8px;">${g.title}</h4>
                ${stepsHtml}
                <button class="outline-btn" style="margin-top:8px;" onclick="app.evaluateGoal(${g.id})">Ziel bewerten & abschließen</button>
            `;
            container.appendChild(div);
        });
    },

    evaluateGoal: function(id) {
        const goal = this.data.activeGoals.find(g => g.id === id);
        if(!goal) return;

        const body = `
            <p>Hast du dieses Ziel erreicht?</p>
            <select id="eval-status" style="width:100%; padding:10px; margin-bottom:10px; border-radius:8px;">
                <option value="Erreicht">Ja, erreicht! 🎉</option>
                <option value="Teilweise">Teilweise erreicht</option>
                <option value="Nicht erreicht">Nein, nicht erreicht</option>
            </select>
            <p>Woran lag es?</p>
            <textarea id="eval-reason" style="width:100%; min-height:60px;" placeholder="Grund oder Reflexion..."></textarea>
        `;

        this.showModal(`Ziel abschließen`, body, () => {
            const status = document.getElementById('eval-status').value;
            const reason = document.getElementById('eval-reason').value;

            const typeTranslated = goal.type === 'daily' ? this.t('goals_daily') : this.t('goals_weekly');
            let journalText = `Ziel (${typeTranslated}): ${goal.title}\n`;
            if(goal.steps.length > 0) journalText += `Schritte:\n- ` + goal.steps.join('\n- ') + `\n\n`;
            journalText += `Ergebnis: ${status}\nReflexion: ${reason}`;

            // Add to Journal
            this.data.entries.push({
                id: Date.now(),
                type: 'goal',
                text: journalText,
                timestamp: new Date().toISOString()
            });

            // Remove from active
            this.data.activeGoals = this.data.activeGoals.filter(g => g.id !== id);
            this.saveData();
            this.renderActiveGoals();
            this.showToast("Ziel ausgewertet und im Tagebuch gespeichert!");
        });
    },

    // --- SUCCESS ---
    saveSuccess: function() {
        const text = document.getElementById('success-input').value;
        const reason = document.getElementById('success-reason').value;

        if(!text) return this.showToast("Bitte gib einen Erfolg ein.");

        let fullText = `Erfolg: ${text}`;
        if(reason) fullText += `\nWarum: ${reason}`;

        this.data.entries.push({
            id: Date.now(),
            type: 'success',
            text: fullText,
            timestamp: new Date().toISOString()
        });

        this.saveData();
        this.triggerConfetti();
        this.showToast("Erfolg gespeichert!");

        document.getElementById('success-input').value = '';
        document.getElementById('success-reason').value = '';
    },

    triggerConfetti: function() {
        for(let i=0; i<60; i++) {
            let el = document.createElement('div');
            el.className = 'confetti';
            el.style.left = (Math.random() * 100) + 'vw';
            el.style.backgroundColor = ['#e11d48', '#d97706', '#4f46e5', '#0d9488'][Math.floor(Math.random()*4)];
            el.style.animationDuration = (Math.random() * 2 + 2) + 's';
            document.body.appendChild(el);
            setTimeout(() => el.remove(), 4000);
        }
    },

    // --- JOURNAL ---
    renderJournal: function() {
        const list = document.getElementById('journal-list');
        list.innerHTML = '';

        if (this.data.entries.length === 0) {
            list.innerHTML = '<p style="text-align:center; color:#94a3b8; margin-top:20px;">Noch keine Einträge vorhanden.</p>';
            return;
        }

        // Group by Date
        const grouped = {};
        const sorted = [...this.data.entries].sort((a,b) => b.id - a.id);

        sorted.forEach(e => {
            const dateObj = new Date(e.timestamp);
            const dateStr = dateObj.toLocaleDateString(this.data.currentLang === 'en' ? 'en-US' : 'de-DE', { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' });
            if(!grouped[dateStr]) grouped[dateStr] = [];
            grouped[dateStr].push(e);
        });

        for (const [date, entries] of Object.entries(grouped)) {
            const dayDiv = document.createElement('div');
            dayDiv.className = 'journal-day-group';
            dayDiv.innerHTML = `<div class="journal-day-header">${date}</div>`;

            entries.forEach(entry => {
                const timeStr = new Date(entry.timestamp).toLocaleTimeString(this.data.currentLang === 'en' ? 'en-US' : 'de-DE', {hour: '2-digit', minute:'2-digit'});
                const div = document.createElement('div');
                div.className = 'journal-entry';

                let emojiHtml = entry.moodEmoji ? `<span style="font-size:20px;">${entry.moodEmoji}</span>` : '';

                div.innerHTML = `
                    <div class="entry-header">
                        <span class="badge ${entry.type}">${entry.type.toUpperCase()}</span>
                        <small>${timeStr} ${emojiHtml}</small>
                    </div>
                    <p id="entry-text-${entry.id}">${entry.text}</p>
                    <div class="entry-actions">
                        <button class="outline-btn" onclick="app.editEntry(${entry.id})">Bearbeiten</button>
                        <button class="danger-btn" onclick="app.deleteEntry(${entry.id})">Löschen</button>
                    </div>
                `;
                dayDiv.appendChild(div);
            });
            list.appendChild(dayDiv);
        }
    },

    editEntry: function(id) {
        const entry = this.data.entries.find(e => e.id === id);
        if(!entry) return;

        const body = `<textarea id="edit-text-val" style="width:100%; min-height:150px;">${entry.text}</textarea>`;
        this.showModal("Eintrag bearbeiten", body, () => {
            const newText = document.getElementById('edit-text-val').value;
            entry.text = newText;
            this.saveData();
            this.renderJournal();
            this.showToast("Geändert!");
        });
    },

    deleteEntry: function(id) {
        this.showModal("Eintrag löschen", "<p>Bist du sicher?</p>", () => {
            this.data.entries = this.data.entries.filter(e => e.id !== id);
            this.saveData();
            this.renderJournal();
            this.showToast("Gelöscht!");
        });
    },

    // --- SETTINGS ---
    updateName: function() {
        const n = document.getElementById('settings-name').value.trim();
        if(n) {
            this.data.user.name = n;
            this.saveData();
            this.showToast("Name gespeichert!");
        }
    },

    confirmReset: function() {
        this.showModal("Daten löschen", "<p style='color:red;'>Wirklich ALLES löschen? Das kann nicht rückgängig gemacht werden!</p>", () => {
            localStorage.clear();
            location.reload();
        });
    },

    applyMaterialYou: function(primary, bg, text, surface) {
        this.data.systemColors = { primary, bg, text, surface };
        const manualColor = localStorage.getItem('aw_manual_colors');
        if (manualColor) {
            const c = JSON.parse(manualColor);
            this.setCssVariables(c.primary, c.surface, c.bg, c.text);
        } else {
            this.setCssVariables(primary, surface, bg, text);
        }
    },
    setManualColor: function(primary, surface, bg, text) {
        localStorage.setItem('aw_manual_colors', JSON.stringify({ primary, surface, bg, text }));
        this.setCssVariables(primary, surface, bg, text);
        this.showToast("Farbschema angewendet!");
    },
    resetToMaterialYou: function() {
        localStorage.removeItem('aw_manual_colors');
        if (this.data.systemColors) {
            const sc = this.data.systemColors;
            this.setCssVariables(sc.primary, sc.surface, sc.bg, sc.text);
            this.showToast("System-Farben aktiv!");
        } else {
            this.showToast("Standardfarben aktiv.");
            this.setCssVariables('#0d9488', '#f0fdfa', '#f8fafc', '#334155');
        }
    },
    setCssVariables: function(p, s, b, t) {
        const root = document.documentElement.style;
        root.setProperty('--primary-teal', p);
        root.setProperty('--soft-teal', s);
        root.setProperty('--bg-color', b);
        root.setProperty('--text-main', t);
    },

    // --- BRIDGE ---
    toggleDailyReminder: function() {
        const timeInput = document.getElementById('reminder-time').value;
        if(window.AndroidApp) {
            window.AndroidApp.scheduleNotification(true, timeInput, this.t('splash_subtitle'));
            this.showToast(`Erinnerung für ${timeInput} Uhr aktiviert!`);
        } else {
            this.showToast("Native Bridge nicht gefunden.");
        }
    },
    exportPdf: function() {
        if(window.AndroidApp) {
            window.AndroidApp.generateAndSavePdf(JSON.stringify(this.data.entries), "Tagebuch.pdf", this.data.user.name);
        } else {
            this.showToast("Native Bridge nicht gefunden.");
        }
    }
};

document.addEventListener("DOMContentLoaded", () => {
    // Event Listener setup for Inputs to hide direct save if typing inside NLP search
    const goalInp = document.getElementById('goal-input');
    if(goalInp) {
        goalInp.addEventListener('input', () => {
            document.getElementById('goal-nlp-suggestions').innerHTML = '';
            document.getElementById('custom-step-container').style.display = 'none';
            document.getElementById('btn-save-goal-direct').style.display = goalInp.value ? 'block' : 'none';
        });
    }

    // Scroll inputs into view to avoid keyboard overlap
    document.querySelectorAll('input[type="text"], textarea').forEach(el => {
        el.addEventListener('focus', () => {
            setTimeout(() => el.scrollIntoView({behavior: 'smooth', block: 'center'}), 300);
        });
    });

    app.init();
});